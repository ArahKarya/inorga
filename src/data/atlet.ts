/** Laju perbaikan aspek inti per event (kemiringan tren) — dasar radar bakat. */
export function kemiringanTren(tren: readonly TrenTitik[]): number {
  if (tren.length < 2) return 0;
  const total = (t: TrenTitik) =>
    Object.values(t.nilai).reduce((a, b) => a + b, 0);
  return (total(tren[tren.length - 1]) - total(tren[0])) / (tren.length - 1);
}
